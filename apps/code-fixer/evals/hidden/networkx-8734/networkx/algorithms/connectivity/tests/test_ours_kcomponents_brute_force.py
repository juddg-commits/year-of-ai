"""Ours (a hidden test for the code fixer's eval, not upstream's): k_components must find every
maximal k-connected node set of a small graph, and nothing that isn't one, checked against brute
force over every node subset. The listed graphs are random ones on which an incomplete fix can
lose or truncate a k-component; the sample adds fresh random graphs."""
import itertools
import random

import pytest

import networkx as nx


def brute_force(G):
    connectivity = {}
    for r in range(2, len(G) + 1):
        for nodes in itertools.combinations(G, r):
            H = G.subgraph(nodes)
            connectivity[frozenset(nodes)] = nx.node_connectivity(H) if nx.is_connected(H) else 0
    out = {}
    for k in range(1, max(connectivity.values(), default=0) + 1):
        sets = [s for s, c in connectivity.items() if c >= k]
        out[k] = sorted(sorted(s) for s in sets if not any(s < t for t in sets))
    return out


def found(G):
    return {k: sorted(sorted(c) for c in comps) for k, comps in nx.k_components(G).items()}


