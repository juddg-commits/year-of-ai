@pytest.mark.parametrize("edges", GRAPHS)
def test_listed_graphs(edges):
    G = nx.Graph(edges)
    assert found(G) == brute_force(G)


@pytest.mark.parametrize("seed", range(10))
def test_random_graphs(seed):
    rng = random.Random(seed)
    for _ in range(15):
        G = nx.gnp_random_graph(rng.randint(5, 9), rng.uniform(0.3, 0.9), seed=rng.randint(0, 10**6))
        assert found(G) == brute_force(G), sorted(G.edges())
