for seed in range(300):
    graphs.append(glued(random.Random(10_000 + seed)))

results = []
for G in graphs:
    try:
        out = ["ok", canon(nx.k_components(G))]
    except Exception as e:
        out = [type(e).__name__]
    results.append([sorted(sorted(e) for e in G.edges()), out])
