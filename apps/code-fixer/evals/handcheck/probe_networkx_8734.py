def canon(comps):
    return {str(k): sorted(sorted(c) for c in v) for k, v in comps.items()}


def glued(rng):
    G, nxt = nx.Graph(), 0
    for _ in range(rng.randint(2, 5)):
        size = rng.randint(3, 6)
        shared = rng.sample(sorted(G.nodes), min(len(G), rng.randint(0, 3)))
        new = list(range(nxt, nxt + max(size - len(shared), 1)))
        nxt += len(new)
        members = shared + new
        G.add_edges_from((a, b) for i, a in enumerate(members) for b in members[i + 1:])
    nodes = sorted(G.nodes)
    for _ in range(rng.randint(0, 3)):
        a, b = rng.sample(nodes, 2)
        G.add_edge(a, b)
    return G


